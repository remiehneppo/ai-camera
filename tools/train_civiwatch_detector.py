"""Training & ONNX Export Pipeline for CiviWatch Detector (640x640).

Supports training modern architectures (YOLO26s / RT-DETRv2 / YOLOv11s)
on the mixed traffic & pedestrian dataset with automated ONNX export
and manifest.json generation conforming to CiviWatch model standards.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import sys
from typing import Any

ROOT = Path(__file__).resolve().parent.parent


def generate_civiwatch_manifest(
    model_name: str,
    onnx_path: Path,
    *,
    input_size: int = 640,
    classes: list[str] | None = None,
    nms_free: bool = True,
    output_name: str = "output0",
    color: str = "RGB",
    scale: float = 1.0 / 255.0,
) -> dict[str, Any]:
    """Generate manifest.json for exported 640x640 CiviWatch detector."""
    blob = onnx_path.read_bytes()
    sha = hashlib.sha256(blob).hexdigest()
    size = len(blob)
    labels = classes or ["person", "two_wheeler", "car", "bus", "truck", "obstacle_object"]

    postprocess_spec: dict[str, Any]
    if nms_free:
        postprocess_spec = {
            "decode": "nms_free",
            "confidence_threshold": 0.25,
            "box_format": "xyxy",
            "person_class_id": 0,
        }
        output_shape = [1, 300, 6]
    else:
        postprocess_spec = {
            "decode": "yolox_grid",
            "strides": [8, 16, 32],
            "score": "objectness_times_class",
            "confidence_threshold": 0.25,
            "nms_threshold": 0.45,
            "nms": "per_class",
            "box_format": "xyxy",
            "person_class_id": 0,
            "candidate_threshold": 0.1,
        }
        # For 640x640 with strides 8,16,32: 80x80 + 40x40 + 20x20 = 6400 + 1600 + 400 = 8400
        output_shape = [1, 8400, len(labels) + 5]

    manifest = {
        "schema_version": 1,
        "model_id": f"civiwatch-{model_name}-640",
        "artifact": {
            "sha256": sha,
            "size_bytes": size,
            "source_url": f"local:{onnx_path.name}",
            "source_commit": "civi-watch-v2",
            "release": "v2.0",
        },
        "input": {
            "name": "images",
            "shape": [1, 3, input_size, input_size],
            "dtype": "float32",
        },
        "output": {
            "name": output_name,
            "shape": output_shape,
            "dtype": "float32",
        },
        "labels": labels,
        "preprocess": {
            "color": color,
            "layout": "NCHW",
            "resize": "bilinear",
            "letterbox": "top_left",
            "pad_value": 114,
            "scale": float(scale),
            "mean": [0.0, 0.0, 0.0],
            "std": [1.0, 1.0, 1.0],
        },
        "postprocess": postprocess_spec,
        "runtime": {
            "onnxruntime": "1.20.1",
            "numpy": "1.26.4",
            "provider": "CPUExecutionProvider",
            "opencv_python_headless": "4.10.0.84",
        },
        "rights": {
            "source_license": "Apache-2.0",
            "weights_license": "internal-lab-civiwatch",
            "lab_use_approved": True,
            "production_use_approved": False,
        },
    }
    return manifest


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--data-yaml",
        type=Path,
        default=ROOT / "data/mixed_traffic/dataset.yaml",
        help="Path to dataset.yaml generated by prepare_mixed_traffic_dataset.py",
    )
    parser.add_argument(
        "--model",
        type=str,
        default="yolo26s",
        help="Model architecture: yolo26s, rtdetr-s, yolo11s, or yolox-s",
    )
    parser.add_argument("--imgsz", type=int, default=640, help="Input image size (default: 640)")
    parser.add_argument("--epochs", type=int, default=50, help="Number of training epochs")
    parser.add_argument("--batch", type=int, default=16, help="Training batch size")
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=ROOT / "models/civiwatch-640",
        help="Directory to save exported ONNX model and manifest.json",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Validate configuration and generate model manifest blueprint without starting GPU training",
    )
    args = parser.parse_args(argv)

    print("=" * 68)
    print("      CIVIWATCH DETECTOR (640x640) TRAINING & EXPORT RUNNER")
    print("=" * 68)
    print(f"Model architecture: {args.model}")
    print(f"Resolution:         {args.imgsz}x{args.imgsz}")
    print(f"Dataset config:     {args.data_yaml}")
    print(f"Output directory:   {args.output_dir}")
    print()

    args.output_dir.mkdir(parents=True, exist_ok=True)

    if not args.data_yaml.is_file():
        print(
            f"[WARNING] Dataset config not found: {args.data_yaml}. "
            "Please run `python tools/prepare_mixed_traffic_dataset.py` first.",
            file=sys.stderr,
        )

    # Check for Ultralytics / PyTorch GPU stack
    try:
        import torch  # type: ignore[import-not-found]
        cuda_avail = torch.cuda.is_available()
        gpu_name = torch.cuda.get_device_name(0) if cuda_avail else "CPU"
        print(f"[ENVIRONMENT] PyTorch {torch.__version__} | Accelerator: {gpu_name} (CUDA available: {cuda_avail})")
    except ImportError:
        torch = None  # type: ignore[assignment]
        cuda_avail = False
        print("[ENVIRONMENT] PyTorch not installed in current environment.")

    if args.dry_run:
        print("[INFO] Generating CiviWatch ONNX preparation blueprint specification & training recipe...")
        try:
            import numpy as np
            import onnx
            from onnx import TensorProto, helper, numpy_helper
        except ImportError as exc:
            print(f"[ERROR] Optional ONNX runtime is required for blueprint specification: {exc}", file=sys.stderr)
            return 1

        blueprint_onnx = args.output_dir / f"{args.model}_civiwatch_{args.imgsz}.blueprint.onnx"
        out_arr = np.zeros((1, 300, 6), dtype=np.float32)
        tensor = numpy_helper.from_array(out_arr, "raw")
        graph = helper.make_graph(
            [helper.make_node("Identity", ["raw"], ["output0"])],
            f"civiwatch-{args.model}-{args.imgsz}-blueprint",
            [helper.make_tensor_value_info("images", TensorProto.FLOAT, [1, 3, args.imgsz, args.imgsz])],
            [helper.make_tensor_value_info("output0", TensorProto.FLOAT, [1, 300, 6])],
            initializer=[tensor],
        )
        onnx_model = helper.make_model(graph, opset_imports=[helper.make_opsetid("", 13)])
        onnx_model.ir_version = 9
        onnx.save(onnx_model, blueprint_onnx)

        manifest = generate_civiwatch_manifest(
            args.model,
            blueprint_onnx,
            input_size=args.imgsz,
            nms_free=True,
        )
        manifest["rights"]["production_use_approved"] = False
        blueprint_manifest_path = args.output_dir / "blueprint_manifest.json"
        blueprint_manifest_path.write_text(json.dumps(manifest, indent=2), encoding="utf-8")
        print(f"[SAVED] Generated CiviWatch {args.imgsz}x{args.imgsz} blueprint manifest at: {blueprint_manifest_path}")

        recipe_sh = args.output_dir / "blueprint_run_training.sh"
        recipe_sh.write_text(
            f"""#!/usr/bin/env bash
# Training command on host GPU (RTX 5060 Ti 16GB):
yolo detect train data={args.data_yaml.resolve()} model={args.model}.pt epochs={args.epochs} imgsz={args.imgsz} batch={args.batch} device=0
# Export to ONNX NMS-free:
yolo export model=runs/detect/train/weights/best.pt format=onnx imgsz={args.imgsz} nms=True
""",
            encoding="utf-8",
        )
        recipe_sh.chmod(0o755)
        print(f"[SAVED] Generated blueprint GPU training recipe: {recipe_sh}")
        print("\n[BLUEPRINT] Preparation-only blueprint generated (not an active deployment).")
        return 0

    if not cuda_avail:
        print(
            "[ERROR] CUDA accelerator is not available for GPU training. "
            "Re-run with --dry-run to generate preparation-only blueprint artifacts without training.",
            file=sys.stderr,
        )
        return 1

    try:
        from ultralytics import YOLO  # type: ignore[import-not-found]
        local_pt = ROOT / "data" / f"{args.model}.pt"
        weights_ref = str(local_pt) if local_pt.is_file() else f"{args.model}.pt"
        print(f"[TRAINING] Launching {args.model} ({weights_ref}) training on {args.data_yaml}...")
        model = YOLO(weights_ref)
        train_results = model.train(
            data=str(args.data_yaml),
            epochs=args.epochs,
            imgsz=args.imgsz,
            batch=args.batch,
            device=0,
            workers=4,
            cache=False,
            project=str(args.output_dir / "runs"),
            name=f"{args.model}_hcmc",
            exist_ok=True,
        )
        best_pt = Path(train_results.save_dir) / "weights/best.pt"
        if not best_pt.is_file():
            best_pt = Path(train_results.save_dir) / "weights/last.pt"
        print(f"[EXPORT] Exporting trained weights ({best_pt}) to NMS-free ONNX format...")
        best_model = YOLO(str(best_pt))
        exported = best_model.export(format="onnx", imgsz=args.imgsz, nms=True)
        exported_path = Path(exported)
        final_onnx = args.output_dir / f"{args.model}_civiwatch_640.onnx"
        shutil.copy2(exported_path, final_onnx)
        manifest = generate_civiwatch_manifest(
            args.model,
            final_onnx,
            input_size=args.imgsz,
            nms_free=True,
            output_name="output0",
            color="RGB",
            scale=1.0 / 255.0,
        )
        (args.output_dir / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
        print(f"[COMPLETED] Exported {final_onnx} and manifest.json successfully!")
        return 0
    except Exception as exc:
        print(f"[ERROR] Training execution failed: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
